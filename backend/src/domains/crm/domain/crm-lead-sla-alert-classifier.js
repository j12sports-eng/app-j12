const { SLA_STATUS } = require("./crm-lead-stage-sla-policy.js");

const CRM_LEAD_SLA_ALERT_STATUS = Object.freeze({
  COMPLETED: "COMPLETED",
  NORMAL: "NORMAL",
  NOT_CONFIGURED: "NOT_CONFIGURED",
  OVERDUE: "OVERDUE",
  UNAVAILABLE: "UNAVAILABLE",
  WARNING: "WARNING",
});

const SLA_TO_ALERT_STATUS = Object.freeze({
  [SLA_STATUS.COMPLETED]: CRM_LEAD_SLA_ALERT_STATUS.COMPLETED,
  [SLA_STATUS.DUE_SOON]: CRM_LEAD_SLA_ALERT_STATUS.WARNING,
  [SLA_STATUS.NOT_CONFIGURED]: CRM_LEAD_SLA_ALERT_STATUS.NOT_CONFIGURED,
  [SLA_STATUS.ON_TRACK]: CRM_LEAD_SLA_ALERT_STATUS.NORMAL,
  [SLA_STATUS.OVERDUE]: CRM_LEAD_SLA_ALERT_STATUS.OVERDUE,
  [SLA_STATUS.UNAVAILABLE]: CRM_LEAD_SLA_ALERT_STATUS.UNAVAILABLE,
});

const ALERT_PRIORITY = Object.freeze({
  [CRM_LEAD_SLA_ALERT_STATUS.OVERDUE]: 0,
  [CRM_LEAD_SLA_ALERT_STATUS.WARNING]: 1,
  [CRM_LEAD_SLA_ALERT_STATUS.UNAVAILABLE]: 2,
  [CRM_LEAD_SLA_ALERT_STATUS.NOT_CONFIGURED]: 3,
  [CRM_LEAD_SLA_ALERT_STATUS.NORMAL]: 4,
  [CRM_LEAD_SLA_ALERT_STATUS.COMPLETED]: 5,
});

/** Maps the canonical SLA result without recalculating thresholds or elapsed time. */
class CrmLeadSlaAlertClassifier {
  classify(slaStatus) {
    return SLA_TO_ALERT_STATUS[slaStatus] || null;
  }
}

module.exports = {
  ALERT_PRIORITY,
  CRM_LEAD_SLA_ALERT_STATUS,
  CrmLeadSlaAlertClassifier,
  SLA_TO_ALERT_STATUS,
};
